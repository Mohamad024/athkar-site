let dhikrSize = 1.35;
let totalTasbih = 0;
let completedCount = 0;
let currentTab = 'morning';

function checkFinished() {
  const list = document.getElementById('adhkarList');
  const remaining = list.querySelectorAll('.card').length;
  if (remaining === 0) {
    const end = document.createElement('div');
    end.className = 'card end-panel';
    end.innerHTML = `
      <h2 style="color:var(--accent); margin-bottom:10px">أحسنت! 🎉</h2>
      <p>أتممت جميع أذكار ${currentTab === 'morning' ? 'الصباح' : 'المساء'}</p>
      <p style="margin:8px 0">🔢 الأذكار المقروئة: <strong>${completedCount}</strong></p>
      <p style="margin:8px 0">📿 الحسنات (مجموع التسبيح): <strong>${totalTasbih}</strong></p>
      <button id="restart" style="margin-top:12px; font-family:inherit; padding:10px 24px; border-radius:10px; border:1px solid var(--border); background:var(--accent-soft); color:var(--text); cursor:pointer">إعادة الأذكار</button>`;
    list.appendChild(end);
    document.getElementById('restart').addEventListener('click', () => {
      totalTasbih = 0;
      completedCount = 0;
      render(currentTab);
    });
  }
}

function render(tab) {
  currentTab = tab;
  const list = document.getElementById('adhkarList');
  list.innerHTML = '';
  ADHKAR[tab].forEach((d, i) => {
    const card = document.createElement('div');
    card.className = 'card';
    card.innerHTML = `
      <div class="dhikr-title">${i + 1}. ${d.title}</div>
      <div class="dhikr-text" style="--dhikr-size:${dhikrSize}rem; font-size:${dhikrSize}rem">${d.text}</div>
      <div class="dhikr-source">المصدر: ${d.source}</div>
      <div class="tasbih">
        <button class="plus">+ تسبيح</button>
        <span class="count">0</span>
        <span class="target">/ من ${d.count}</span>
        <button class="reset">إعادة</button>
      </div>`;
    const countEl = card.querySelector('.count');
    card.querySelector('.plus').addEventListener('click', () => {
      const n = Number(countEl.textContent) + 1;
      countEl.textContent = n;
      totalTasbih++;
      if (n >= d.count) {
        completedCount++;
        card.style.transition = 'opacity .5s';
        card.style.opacity = '0';
        setTimeout(() => { card.remove(); checkFinished(); }, 500);
      }
    });
    card.querySelector('.reset').addEventListener('click', () => {
      countEl.textContent = 0;
    });
    list.appendChild(card);
  });
}

document.querySelectorAll('.tab').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.tab').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    totalTasbih = 0;
    completedCount = 0;
    render(btn.dataset.tab);
  });
});

document.getElementById('fontInc').addEventListener('click', () => {
  dhikrSize = Math.min(dhikrSize + 0.15, 2.6);
  document.querySelectorAll('.dhikr-text').forEach(el => el.style.fontSize = dhikrSize + 'rem');
});

document.getElementById('fontDec').addEventListener('click', () => {
  dhikrSize = Math.max(dhikrSize - 0.15, 0.9);
  document.querySelectorAll('.dhikr-text').forEach(el => el.style.fontSize = dhikrSize + 'rem');
});

document.getElementById('themeToggle').addEventListener('click', () => {
  document.body.classList.toggle('dark');
  document.getElementById('themeToggle').textContent =
    document.body.classList.contains('dark') ? '☀️' : '🌙';
});

render('morning');
